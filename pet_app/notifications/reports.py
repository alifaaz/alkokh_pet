# A repeat tap re-sends: the customer pressed a button that promised a report, so they
# get one. This guards only against the same tap being answered twice - a Meta webhook
# redelivery, or a double press - and a minute is wide enough to cover both while staying
# far below any interval a person would call "asking again".
DOUBLE_FIRE_SECONDS = 60


def enqueue_reply_report_delivery(message, conversation):
	"""Queue the report a tap was promised, if this reply is one that was promised one.

	Called from the inbound webhook. Everything expensive happens in the background job:
	the webhook must not make an outbound HTTP call inline, because dedup writes
	processed=1 only after _apply_event returns (webhook.py:34-43), so a slow send would
	let Meta redeliver into the unique constraint on the stored event row. This would be
	the first inbound path making such a call, so the rule gets stated rather than
	assumed.

	enqueue_after_commit means a rolled-back webhook sends nothing. The deduplicating
	job_id catches a redelivery that is already queued; the job re-checks against the
	database anyway, because a job id only exists while its job does.
	"""
	target = resolve_reply_report(message)
	if not target:
		return None

	frappe.enqueue(
		"pet_app.notifications.reports.send_reply_report",
		queue="short",
		enqueue_after_commit=True,
		job_id=_delivery_job_id(conversation.name, target["source_doctype"], target["source_name"]),
		deduplicate=True,
		conversation_name=conversation.name,
		file_name=target["file"]["name"],
		inbound_message=message.name,
	)
	return target


def resolve_reply_report(message):
	"""What a reply should be answered with, or None. A pure lookup - it sends nothing.

	The chain, all of it indexed reads:

	    inbound.replied_to_message   the wamid Meta sent as message.context.id (p1_25)
	      -> outbound message        which carries source_doctype / source_name already
	      -> its notification queue  which names the Meta template that was sent
	      -> the mirror row          which says whether that template promised a report

	Nothing here names a template or a doctype. A radiology template promising an Imaging
	report resolves through exactly these four reads with nothing added.
	"""
	replied_to = message.get("replied_to_message")
	if not replied_to:
		return None

	outbound = frappe.db.get_value(
		"Pet App WhatsApp Message",
		replied_to,
		["name", "direction", "notification_queue", "source_doctype", "source_name"],
		as_dict=True,
	)
	# A guardian can quote their own earlier message; that is a reply to us about
	# nothing we promised.
	if not outbound or outbound.direction != "Outbound" or not outbound.notification_queue:
		return None
	if not outbound.source_doctype or not outbound.source_name:
		return None

	meta_template = frappe.db.get_value(
		"Pet App Notification Queue", outbound.notification_queue, "meta_template"
	)
	if not meta_template:
		return None

	from pet_app.notifications.meta_templates import promises_reviewed_report

	if not promises_reviewed_report(meta_template):
		return None

	report = newest_reviewed_report(outbound.source_doctype, outbound.source_name)
	if not report:
		# Phase 3 refuses a send with no report attached, so reaching here means the
		# report was removed between the promise and the tap. Worth a line in the log:
		# a guardian is waiting for something nobody can send them.
		frappe.logger("pet_app.whatsapp_report").warning(
			"Tap on %s promised a report for %s %s, and none is attached.",
			outbound.name,
			outbound.source_doctype,
			outbound.source_name,
		)
		return None

	return {
		"outbound_message": outbound.name,
		"source_doctype": outbound.source_doctype,
		"source_name": outbound.source_name,
		"meta_template": meta_template,
		"file": report,
	}


def send_reply_report(conversation_name, file_name, inbound_message=None):
	"""The background job. Sends the stored file, and never regenerates it.

	Runs as Administrator because the webhook that scheduled it is allow_guest, and
	frappe.enqueue carries the calling session's user with no way to override it - so
	without this the job runs as Guest and send_conversation_message's read permission
	check on a now-private file fails, which is the silent no-op this whole change
	exists to remove. The actor genuinely is the system: no person is at a keyboard, and
	the authorisation is the guardian's own tap.

	Consent and rate limits are deliberately still enforced - they live inside
	send_conversation_message and a system actor is not a reason to skip them.
	"""
	frappe.set_user("Administrator")

	from pet_app.notifications.inbox import notify_inbox_users, send_conversation_message

	if _already_sent_within_double_fire_window(conversation_name, file_name):
		frappe.logger("pet_app.whatsapp_report").info(
			"Skipping report %s to %s: an identical send is less than %ss old.",
			file_name,
			conversation_name,
			DOUBLE_FIRE_SECONDS,
		)
		return None

	try:
		return send_conversation_message(conversation_name, file_name=file_name)
	except Exception:
		# A guardian has been told a report is coming and it is not. That cannot be a
		# line in the error log nobody reads, so it also lands in the inbox where staff
		# are already looking at this conversation.
		frappe.log_error(
			title="WhatsApp reviewed report delivery failed",
			message=(
				f"conversation={conversation_name} file={file_name} "
				f"inbound_message={inbound_message}\n\n{frappe.get_traceback()}"
			),
		)
		conversation = frappe.get_doc("Pet App WhatsApp Conversation", conversation_name)
		message = (
			frappe.get_doc("Pet App WhatsApp Message", inbound_message)
			if inbound_message and frappe.db.exists("Pet App WhatsApp Message", inbound_message)
			else None
		)
		if message:
			notify_inbox_users(
				conversation,
				message,
				subject=_("A promised report could not be sent - send it manually"),
			)
		raise


def _already_sent_within_double_fire_window(conversation_name, file_name) -> bool:
	"""Whether this exact file went to this conversation moments ago.

	The authoritative guard, checked in the job rather than at enqueue time: two webhook
	deliveries racing can both pass the queue's dedup before either has enqueued, and a
	job id stops existing once its job finishes.

	Scoped to this file rather than to the record, so a corrected report attached
	seconds after the first one still goes out - it is a different file, and the customer
	is owed the corrected one.
	"""
	from frappe.utils import add_to_date

	return bool(
		frappe.db.exists(
			"Pet App WhatsApp Message",
			{
				"conversation": conversation_name,
				"direction": "Outbound",
				"file": file_name,
				"message_at": [">=", add_to_date(now_datetime(), seconds=-DOUBLE_FIRE_SECONDS)],
			},
		)
	)


def _delivery_job_id(conversation_name, source_doctype, source_name) -> str:
	"""One job per conversation, record and minute.

	The minute bucket is what makes a repeat tap a minute later a real re-send rather
	than a job id collision, which is the agreed behaviour: the customer pressed a button
	that promised a report, so they get one.
	"""
	minute = now_datetime().strftime("%Y%m%d%H%M")
	return f"pet-app-reply-report:{conversation_name}:{source_doctype}:{source_name}:{minute}"
